// One-off extraction of remend test cases into JSON fixtures for StreamMark.
//
// Runs the original vitest suites of vercel/streamdown packages/remend
// (Apache-2.0, Copyright 2023 Vercel, Inc.) under a small vitest shim and
// records every call a test makes into the remend sources together with the
// TypeScript result. The TS suite is asserted while recording, so every
// recorded result is the behavior the TS tests verify.
//
// Usage (Node >= 23.6 for native TypeScript type stripping):
//   npm install --prefix <deps> fast-check@4 mdast-util-from-markdown@2
//   node extract.mjs <path-to>/packages/remend <deps> <out-dir>
import { readdirSync, writeFileSync } from "node:fs";
import { register } from "node:module";
import { basename, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const [pkgDir, depsDir, outDir] = process.argv.slice(2).map((p) => resolve(p));
if (!outDir) {
  console.error("usage: node extract.mjs <remend-package-dir> <deps-dir> <out-dir>");
  process.exit(2);
}

register("./hooks.mjs", import.meta.url, {
  data: { pkgUrl: pathToFileURL(pkgDir).href, depsDir },
});

const { state } = await import("./recorder.mjs");
const shim = await import("./vitest-shim.mjs");
const fc = (await import(pathToFileURL(`${depsDir}/node_modules/fast-check/lib/fast-check.js`).href)).default;
// Deterministic property runs
fc.configureGlobal({ seed: 20231031 });

// Generated (property-based) suites record only a bounded sample per test
const SAMPLED = new Set(["streaming-properties.test.ts", "trailing-patterns.test.ts"]);
const SAMPLE_CAP = 600;

const HEADER =
  "Generated by tools/remend-fixtures/extract.mjs from the test suite of vercel/streamdown " +
  "packages/remend (Apache-2.0, Copyright 2023 Vercel, Inc.); modified: sentinel URLs use " +
  "the streammark: scheme. Each case is a top-level call into the remend sources with the " +
  "result of the TypeScript implementation.";

const rename = (value) => {
  if (typeof value === "string") return value.replaceAll("streamdown:incomplete-", "streammark:incomplete-");
  if (Array.isArray(value)) return value.map(rename);
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, rename(v)]));
  }
  return value;
};

const testDir = `${pkgDir}/__tests__`;
const files = readdirSync(testDir).filter((f) => f.endsWith(".test.ts")).sort();
let total = 0;
for (const file of files) {
  state.file = file;
  state.records = [];
  state.cap = SAMPLED.has(file) ? SAMPLE_CAP : Number.POSITIVE_INFINITY;
  state.uncapped = (test) => test.startsWith("exhaustive prefix sweep");
  await import(pathToFileURL(`${testDir}/${file}`).href);
  const cases = state.records.map(rename);
  total += cases.length;
  const name = basename(file, ".test.ts");
  writeFileSync(
    `${outDir}/${name}.json`,
    // One case per line keeps the files diffable
    `{\n "_comment": ${JSON.stringify(HEADER)},\n "source": ${JSON.stringify(`packages/remend/__tests__/${file}`)},\n "cases": [\n` +
      cases.map((c) => `  ${JSON.stringify(c)}`).join(",\n") +
      "\n ]\n}\n"
  );
  console.log(`${file}: ${cases.length} cases`);
}

console.log(`total ${total} cases, ${state.skipped} unserializable calls skipped`);
console.log(`TS tests: ${shim.passed} passed, ${shim.failures.length} failed`);
for (const f of shim.failures) console.log(`FAIL ${f.file} :: ${f.test}\n  ${f.message.slice(0, 400)}`);
